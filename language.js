  function translateString(value) {
    if (!value) return value;
    const text = value.trim();
    if (!text) return value;
    if (FR[text]) return value.replace(text, FR[text]);

    let match = text.match(/^Explore (.+)$/);
    if (match) {
      const name = CATEGORY_FR[match[1]] || match[1];
      return value.replace(text, `Découvrir ${name}`);
    }

    match = text.match(/^(\d+) products selected$/);
    if (match) {
      const n = Number(match[1]);
      return value.replace(text, `${n} produit${n === 1 ? '' : 's'} sélectionné${n === 1 ? '' : 's'}`);
    }

    match = text.match(/^(\d+) cases$/);
    if (match) {
      const n = Number(match[1]);
      return value.replace(text, `${n} carton${n === 1 ? '' : 's'}`);
    }

    match = text.match(/^(\d+) products · (\d+) cases$/);
    if (match) {
      const p = Number(match[1]);
      const c = Number(match[2]);
      return value.replace(text, `${p} produit${p === 1 ? '' : 's'} · ${c} carton${c === 1 ? '' : 's'}`);
    }

    const suffix = '. Discover authentic Shama products selected for homes, restaurants and retailers across France.';
    if (text.endsWith(suffix)) {
      const desc = text.slice(0, -suffix.length);
      const frDesc = DESCRIPTION_FR[desc] || desc;
      return value.replace(text, `${frDesc}. Découvrez des produits Shama authentiques sélectionnés pour les foyers, restaurants et détaillants partout en France.`);
    }

    return value;
  }

  function shouldSkipText(node) {
    const parent = node.parentElement;
    if (!parent) return true;
    return /^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA)$/i.test(parent.tagName);
  }

  function captureNode(node, force = false) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (!shouldSkipText(node) && (force || !originalText.has(node))) originalText.set(node, node.nodeValue);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_NODE && node.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;

    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    let textNode;
    while ((textNode = walker.nextNode())) {
      if (!shouldSkipText(textNode) && (force || !originalText.has(textNode))) originalText.set(textNode, textNode.nodeValue);
    }

    if (node.nodeType === Node.ELEMENT_NODE) captureAttributes(node, force);
    if (node.querySelectorAll) node.querySelectorAll('[aria-label], [title], [placeholder]').forEach(el => captureAttributes(el, force));
  }

  function captureAttributes(el, force = false) {
    let map = originalAttrs.get(el);
    if (!map) {
      map = {};
      originalAttrs.set(el, map);
    }
    ['aria-label', 'title', 'placeholder'].forEach(attr => {
      if (el.hasAttribute(attr) && (force || !(attr in map))) map[attr] = el.getAttribute(attr);
    });
  }

  function applyLanguage(lang) {
    currentLanguage = lang;
    document.documentElement.lang = lang;
    document.documentElement.dataset.language = lang;

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (shouldSkipText(node)) continue;
      if (!originalText.has(node)) originalText.set(node, node.nodeValue);
      const english = originalText.get(node);
      node.nodeValue = lang === 'fr' ? translateString(english) : english;
    }

    document.querySelectorAll('[aria-label], [title], [placeholder]').forEach(el => {
      captureAttributes(el);
      const attrs = originalAttrs.get(el) || {};
      Object.entries(attrs).forEach(([attr, english]) => {
        el.setAttribute(attr, lang === 'fr' ? translateString(english) : english);
      });
    });

    if (lang === 'fr') {
      document.title = 'Shama International | Saveurs Authentiques';
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute('content', 'Shama International — des saveurs authentiques, sélectionnées avec soin.');
    } else {
      document.title = 'Shama International | Authentic Flavours';
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute('content', 'Shama International — authentic flavours, thoughtfully sourced.');
    }

    document.querySelectorAll('.shama-lang-button').forEach(button => {
      const active = button.dataset.lang === lang;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', active ? 'true' : 'false');
    });
  }

  function observe() {
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['aria-label', 'title', 'placeholder']
    });
  }

  function applyWithObserverPaused(lang) {
    if (observer) observer.disconnect();
    applyLanguage(lang);
    if (observer) observe();
  }

  function setLanguage(lang, remember = true) {
    const next = lang === 'fr' ? 'fr' : 'en';
    if (remember) {
      try { localStorage.setItem('shama-language', next); } catch (_) {}
    }
    applyWithObserverPaused(next);
  }

  function addSwitcher() {
    const nav = document.querySelector('.nav-shell');
    if (!nav || nav.querySelector('.shama-lang-switch')) return;
    const switcher = document.createElement('div');
    switcher.className = 'shama-lang-switch';
    switcher.setAttribute('role', 'group');
    switcher.setAttribute('aria-label', 'Choose language');
    switcher.innerHTML = '<button type="button" class="shama-lang-button" data-lang="en" aria-pressed="false">EN</button><button type="button" class="shama-lang-button" data-lang="fr" aria-pressed="false">FR</button>';
    const cta = nav.querySelector('.header-cta');
    nav.insertBefore(switcher, cta || null);
    switcher.addEventListener('click', event => {
      const button = event.target.closest('.shama-lang-button');
      if (button) setLanguage(button.dataset.lang);
    });
  }

